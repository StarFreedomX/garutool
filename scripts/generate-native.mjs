import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { toolCatalog } from '../src/config/tools.ts'

const root = fileURLToPath(new URL('..', import.meta.url))
const output = resolve(process.argv[2] ?? join(root, 'android/app/build/generated/toolkit'))
const drawables = join(output, 'res/drawable')
const java = join(output, 'java/io/github/garutool')
await Promise.all([mkdir(drawables, { recursive: true }), mkdir(java, { recursive: true })])

const icons = (await readdir(join(root, 'assets/icons')))
  .filter((name) => name.endsWith('.svg'))
  .sort()
const attribute = (source, key) => source.match(new RegExp(`\\b${key}="([^"]+)"`))?.[1]
for (const name of icons) {
  const svg = await readFile(join(root, 'assets/icons', name), 'utf8')
  const [left, top, width, height] = attribute(svg, 'viewBox').split(/\s+/).map(Number)
  if (left !== 0 || top !== 0 || !width || !height) throw new Error(`Unsupported viewBox: ${name}`)
  const paths = [...svg.matchAll(/<path\s[^>]*>/g)].map(([path]) => {
    const data = attribute(path, 'd')
    if (!data) throw new Error(`Missing path: ${name}`)
    return `    <path android:pathData="${data}" android:fillColor="@android:color/transparent" android:strokeColor="#FFFFFFFF" android:strokeWidth="${attribute(svg, 'stroke-width') ?? '2'}" android:strokeLineCap="round" android:strokeLineJoin="round" />`
  })
  if (!paths.length) throw new Error(`No paths: ${name}`)
  const xml = `<?xml version="1.0" encoding="utf-8"?>\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="${width}" android:viewportHeight="${height}">\n${paths.join('\n')}\n</vector>\n`
  await writeFile(join(drawables, `ic_${name.slice(0, -4)}.xml`), xml)
}

const iconNames = icons.map((name) => name.slice(0, -4))
for (const action of toolCatalog.actions) {
  if (!iconNames.includes(action.icon)) throw new Error(`Missing icon: ${action.icon}`)
}
await writeFile(
  join(java, 'ToolAssets.java'),
  `// Generated by scripts/generate-native.mjs.\npackage io.github.garutool;\n\npublic final class ToolAssets {\n    public static final String CATALOG_JSON = ${JSON.stringify(JSON.stringify(toolCatalog))};\n\n    public static int icon(String name) {\n        return switch (name) {\n${iconNames.map((name) => `            case "${name}" -> R.drawable.ic_${name};`).join('\n')}\n            default -> throw new IllegalArgumentException("Unknown tool icon: " + name);\n        };\n    }\n}\n`,
)

for (const [theme, colors] of Object.entries(toolCatalog.themes)) {
  const directory = join(output, 'res', theme === 'dark' ? 'values-night' : 'values')
  await mkdir(directory, { recursive: true })
  await writeFile(
    join(directory, 'tool_colors.xml'),
    `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="surface">${colors.surface}</color>\n    <color name="accent">${colors.accent}</color>\n    <color name="launcher_background">${toolCatalog.themes.light.accent}</color>\n</resources>\n`,
  )
}
